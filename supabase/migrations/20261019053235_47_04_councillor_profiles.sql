-- Councillor profile overviews (read by the web profile tab, written by
-- pipeline/profiling/profile_agent.py). Missing from the Langford database:
-- 39-key-votes-table.sql only ALTERed this table, and the per-person vector
-- search RPCs the profile agent calls were never created.

CREATE TABLE IF NOT EXISTS councillor_highlights (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id bigint NOT NULL UNIQUE REFERENCES people(id) ON DELETE CASCADE,
  highlights jsonb NOT NULL DEFAULT '[]'::jsonb,
  overview text,
  narrative text,
  narrative_generated_at timestamptz,
  generated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE councillor_highlights ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow public read access to councillor highlights" ON councillor_highlights;
CREATE POLICY "Allow public read access to councillor highlights"
  ON councillor_highlights FOR SELECT TO anon, authenticated USING (true);

CREATE OR REPLACE FUNCTION public.match_key_statements_by_person(
  query_embedding halfvec,
  filter_person_id bigint,
  match_threshold double precision,
  match_count integer
)
RETURNS TABLE(id bigint, meeting_id bigint, agenda_item_id bigint, speaker_name text,
              statement_type text, statement_text text, context text, similarity double precision)
LANGUAGE sql STABLE
SET search_path TO 'public'
AS $$
  SELECT ks.id, ks.meeting_id, ks.agenda_item_id, ks.speaker_name,
         ks.statement_type, ks.statement_text, ks.context,
         1 - (ks.embedding <=> query_embedding) AS similarity
  FROM key_statements ks
  WHERE ks.person_id = filter_person_id
    AND ks.embedding IS NOT NULL
    AND 1 - (ks.embedding <=> query_embedding) > match_threshold
  ORDER BY ks.embedding <=> query_embedding
  LIMIT match_count;
$$;

-- Motions the person voted on, with their recorded vote.
CREATE OR REPLACE FUNCTION public.match_motions_by_person(
  query_embedding halfvec,
  filter_person_id bigint,
  match_threshold double precision,
  match_count integer
)
RETURNS TABLE(id bigint, meeting_id bigint, text_content text, result text,
              vote text, similarity double precision)
LANGUAGE sql STABLE
SET search_path TO 'public'
AS $$
  SELECT m.id, m.meeting_id, m.text_content, m.result, v.vote,
         1 - (m.embedding <=> query_embedding) AS similarity
  FROM motions m
  JOIN votes v ON v.motion_id = m.id AND v.person_id = filter_person_id
  WHERE m.embedding IS NOT NULL
    AND 1 - (m.embedding <=> query_embedding) > match_threshold
  ORDER BY m.embedding <=> query_embedding
  LIMIT match_count;
$$;

CREATE INDEX IF NOT EXISTS idx_key_statements_person ON key_statements (person_id);
