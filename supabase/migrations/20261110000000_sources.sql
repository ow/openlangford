-- Sources outside the meeting record. Land purchases, settlements and hires happen in closed meetings (Community
-- Charter s.90), so the open record often only shows their aftermath. A source is a dated statement from somewhere
-- else: a City news release or notice (origin 'city'), a news report (origin 'press'), or another document (origin
-- 'other'), with the words it says (quote), a resident-register line saying what happened (headline), the date it
-- happened (happened_on) and a link. Staff add them from the page review bar; the fix agent never invents one.
--
-- public_reports stays what it is: the City's own page-indexed documents (annual reports), read by the pipeline.
-- A source is a link plus a quote, added by hand, and labelled on the page by who said it.
--
-- Links rot (the 2019 Victoria News story on the 3680 Trans-Canada purchase is gone from vicnews.com), so adding a
-- source keeps the page's text privately for the checks and asks the Wayback Machine for a public copy.
--
-- Safe on live data: two new tables, no change to existing rows.

CREATE TABLE public.sources (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    municipality_id bigint NOT NULL REFERENCES public.municipalities(id),
    origin text NOT NULL CHECK (origin = ANY (ARRAY['city'::text, 'press'::text, 'other'::text])),
    publisher text NOT NULL,              -- "City of Langford", "Victoria News", "CHEK News"
    title text NOT NULL,                  -- the page or article's own title
    url text,
    published_on date,                    -- when the source was published
    happened_on date NOT NULL,            -- when the thing it reports happened (defaults to published_on when unknown)
    headline text NOT NULL,               -- resident register, one line: "City buys the 22-acre waterfront lot for about $2.2M"
    quote text,                           -- the source's own words that back the headline
    note text,                            -- staff's note on why it's here (not shown to residents)
    content_text text,                    -- the page's readable text at the time it was added, for checks (never shown)
    content_fetched_at timestamp with time zone,
    archive_url text,                     -- a Wayback Machine copy, requested when the source is added
    archived_at timestamp with time zone,
    added_by uuid,
    hidden boolean NOT NULL DEFAULT false,
    meta jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);
COMMENT ON TABLE public.sources IS 'Dated statements from outside the meeting record (City releases and notices, news reports), added by staff from the review bar. Labelled on the page by who said it; never part of the record layer.';

CREATE TABLE public.source_links (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id bigint NOT NULL REFERENCES public.sources(id) ON DELETE CASCADE,
    matter_id bigint REFERENCES public.matters(id) ON DELETE CASCADE,
    property_id bigint REFERENCES public.properties(id) ON DELETE CASCADE,
    hidden boolean NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT source_links_target CHECK (matter_id IS NOT NULL OR property_id IS NOT NULL)
);
CREATE UNIQUE INDEX source_links_matter_idx ON public.source_links (source_id, matter_id) WHERE matter_id IS NOT NULL;
CREATE UNIQUE INDEX source_links_property_idx ON public.source_links (source_id, property_id) WHERE property_id IS NOT NULL;
CREATE INDEX source_links_by_matter ON public.source_links (matter_id);
CREATE INDEX source_links_by_property ON public.source_links (property_id);

-- A link to a merged topic lands on the one it was merged into, like every other matter link.
CREATE TRIGGER redirect_merged_matter BEFORE INSERT OR UPDATE OF matter_id ON public.source_links
  FOR EACH ROW WHEN (NEW.matter_id IS NOT NULL) EXECUTE FUNCTION public.redirect_merged_matter();

-- Public pages change when a source is added or edited: cache version and the topic's freshness stamp.
CREATE TRIGGER touch_public_content_version AFTER INSERT OR DELETE OR UPDATE OR TRUNCATE ON public.sources
  FOR EACH STATEMENT EXECUTE FUNCTION public.touch_public_content_version();
CREATE TRIGGER touch_public_content_version AFTER INSERT OR DELETE OR UPDATE OR TRUNCATE ON public.source_links
  FOR EACH STATEMENT EXECUTE FUNCTION public.touch_public_content_version();

CREATE OR REPLACE FUNCTION public.bump_matter_content_source() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
begin
  update matters set content_updated_at = now()
  where id = coalesce(new.matter_id, old.matter_id) and content_updated_at is distinct from now();
  return null;
end $$;
CREATE TRIGGER bump_matter_content_source AFTER INSERT OR DELETE OR UPDATE ON public.source_links
  FOR EACH ROW EXECUTE FUNCTION public.bump_matter_content_source();

CREATE OR REPLACE FUNCTION public.set_updated_at_sources() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
begin
  new.updated_at = now();
  return new;
end $$;
CREATE TRIGGER set_updated_at BEFORE UPDATE ON public.sources FOR EACH ROW EXECUTE FUNCTION public.set_updated_at_sources();

ALTER TABLE public.sources ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.source_links ENABLE ROW LEVEL SECURITY;
CREATE POLICY "sources public read" ON public.sources FOR SELECT TO authenticated, anon USING ((NOT hidden));
CREATE POLICY "source_links public read" ON public.source_links FOR SELECT TO authenticated, anon USING ((NOT hidden));
GRANT SELECT ON TABLE public.sources TO anon, authenticated;
GRANT SELECT ON TABLE public.source_links TO anon, authenticated;
GRANT ALL ON TABLE public.sources TO service_role;
GRANT ALL ON TABLE public.source_links TO service_role;
