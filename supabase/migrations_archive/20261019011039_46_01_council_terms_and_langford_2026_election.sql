-- Council tenure is distinct from election day and from a person's identity.
-- End dates are inclusive. An unknown future term end stays NULL.
BEGIN;

ALTER TABLE elections
    ADD COLUMN IF NOT EXISTS results_status text NOT NULL DEFAULT 'pending',
    ADD COLUMN IF NOT EXISTS source_url text;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'elections'::regclass AND conname = 'elections_results_status_check') THEN
        ALTER TABLE elections ADD CONSTRAINT elections_results_status_check
            CHECK (results_status IN ('pending', 'preliminary', 'official'));
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS council_terms (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    municipality_id bigint NOT NULL REFERENCES municipalities(id) ON DELETE CASCADE,
    election_id bigint REFERENCES elections(id) ON DELETE SET NULL,
    name text NOT NULL,
    start_date date NOT NULL,
    end_date date,
    meta jsonb,
    created_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT council_terms_dates_check CHECK (end_date IS NULL OR end_date >= start_date),
    UNIQUE (municipality_id, start_date)
);

COMMENT ON TABLE council_terms IS 'Municipal council tenures, beginning at the inaugural meeting, not election day.';
COMMENT ON COLUMN council_terms.end_date IS 'Inclusive last day; NULL when the next inauguration is not yet confirmed.';

CREATE INDEX IF NOT EXISTS idx_council_terms_election_id ON council_terms(election_id);
DROP TRIGGER IF EXISTS set_timestamp_council_terms ON council_terms;
CREATE TRIGGER set_timestamp_council_terms BEFORE UPDATE ON council_terms
    FOR EACH ROW EXECUTE PROCEDURE update_timestamp();

ALTER TABLE memberships ADD COLUMN IF NOT EXISTS council_term_id bigint REFERENCES council_terms(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_memberships_council_term_id ON memberships(council_term_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_memberships_person_org_role_term
    ON memberships(person_id, organization_id, role, council_term_id)
    WHERE council_term_id IS NOT NULL;

ALTER TABLE council_terms ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow public read-only access on council_terms" ON council_terms;
CREATE POLICY "Allow public read-only access on council_terms" ON council_terms FOR SELECT TO public USING (true);
GRANT SELECT ON council_terms TO anon, authenticated;
GRANT ALL ON council_terms TO service_role;
GRANT USAGE, SELECT ON SEQUENCE council_terms_id_seq TO service_role;

-- Seed only Langford. Reuse existing people, especially those whose transcript
-- identities use initials. Never replace permanent person IDs or historical votes.
-- Evidence checked 2026-10-18:
-- 2022 inaugural minutes: https://pub-langford.escribemeetings.com/filestream.ashx?DocumentId=4014
-- 2026 dates/city-endorsed results link: https://langford.ca/election-2026/
-- Results (updated Oct 18, 5:55pm): https://localelections.ca/election_results/60_2026_results.html
-- CivicInfo's elected checkmarks establish the preliminary winners, not a
-- certified declaration. Preserve an existing 'official' status on rerun.
DO $$
DECLARE
    municipality bigint;
    council bigint;
    election_2022 bigint;
    election_2026 bigint;
    term_2022 bigint;
    term_2026 bigint;
    office_id bigint;
    person bigint;
    candidate record;
BEGIN
    SELECT id INTO municipality FROM municipalities WHERE slug = 'langford';
    IF municipality IS NULL THEN RETURN; END IF;
    SELECT id INTO council FROM organizations
        WHERE municipality_id = municipality AND classification = 'Council' AND name = 'Council';
    IF council IS NULL THEN
        RAISE EXCEPTION 'Langford Council organization must exist before seeding council terms';
    END IF;

    INSERT INTO elections (name, election_date, classification, term_length_years, results_status, source_url)
    VALUES ('2022 General Local Election', DATE '2022-10-15', 'General', 4, 'official',
        'https://pub-langford.escribemeetings.com/filestream.ashx?DocumentId=4014')
    ON CONFLICT (name) DO UPDATE SET results_status = 'official', source_url = EXCLUDED.source_url
    RETURNING id INTO election_2022;

    INSERT INTO elections (name, election_date, classification, term_length_years, results_status, source_url, notes)
    VALUES ('2026 General Local Election', DATE '2026-10-17', 'General', 4, 'preliminary',
        'https://localelections.ca/election_results/60_2026_results.html',
        'Preliminary results reported by CivicInfo BC, linked by the City of Langford; checked October 18, 2026. Scheduled inaugural meeting: November 2, 2026. Winners are incoming until that date.')
    ON CONFLICT (name) DO UPDATE SET
        results_status = CASE WHEN elections.results_status = 'official' THEN 'official' ELSE EXCLUDED.results_status END,
        source_url = EXCLUDED.source_url,
        notes = CASE WHEN elections.results_status = 'official' THEN elections.notes ELSE EXCLUDED.notes END
    RETURNING id INTO election_2026;

    INSERT INTO council_terms (municipality_id, election_id, name, start_date, end_date, meta)
    VALUES (municipality, election_2022, '2022–2026 Council', DATE '2022-11-07', DATE '2026-11-01',
        '{"start_source_url":"https://pub-langford.escribemeetings.com/filestream.ashx?DocumentId=4014","end_source_url":"https://langford.ca/election-2026/","end_basis":"Day before the scheduled November 2, 2026 inauguration"}'::jsonb)
    ON CONFLICT (municipality_id, start_date) DO UPDATE SET election_id = EXCLUDED.election_id, name = EXCLUDED.name,
        end_date = COALESCE(council_terms.end_date, EXCLUDED.end_date), meta = COALESCE(council_terms.meta, '{}'::jsonb) || EXCLUDED.meta
    RETURNING id INTO term_2022;

    INSERT INTO council_terms (municipality_id, election_id, name, start_date, end_date, meta)
    VALUES (municipality, election_2026, '2026 Council', DATE '2026-11-02', NULL,
        '{"start_source_url":"https://langford.ca/election-2026/","start_basis":"Scheduled inaugural meeting; not yet sworn in as of October 18, 2026"}'::jsonb)
    ON CONFLICT (municipality_id, start_date) DO UPDATE SET election_id = EXCLUDED.election_id, name = EXCLUDED.name,
        meta = COALESCE(council_terms.meta, '{}'::jsonb) || EXCLUDED.meta
    RETURNING id INTO term_2026;

    -- Correct only known 2022 Council rows, not committee appointments or staff.
    -- Preserve earlier departures, including Lillian Szpak's May 2, 2026 vacancy.
    UPDATE memberships m SET
        council_term_id = term_2022,
        start_date = DATE '2022-11-07',
        end_date = CASE WHEN m.end_date IS NULL OR m.end_date > DATE '2026-11-01' THEN DATE '2026-11-01' ELSE m.end_date END
    FROM people p
    WHERE m.person_id = p.id AND m.organization_id = council
      AND m.role IN ('Mayor', 'Councillor')
      AND m.start_date IN (DATE '2022-11-01', DATE '2022-11-07')
      AND (m.council_term_id IS NULL OR m.council_term_id = term_2022)
      AND p.name IN ('S. Goodmanson', 'Scott Goodmanson', 'K. Guiry', 'Kimberley Guiry', 'C. Harder', 'Colby Harder',
          'M. Morley', 'Mark Morley', 'M. Wagner', 'Mary Wagner', 'K. Yacucha', 'Keith Yacucha', 'L. Szpak', 'Lillian Szpak');

    -- A later certified import owns its roster and vote totals. Replaying this
    -- preliminary snapshot must not recreate candidates or memberships it removed.
    IF (SELECT results_status FROM elections WHERE id = election_2026) = 'official' THEN RETURN; END IF;

    INSERT INTO election_offices (election_id, office, seats_available)
    VALUES (election_2026, 'Mayor', 1), (election_2026, 'Councillor', 6)
    ON CONFLICT (election_id, office) DO UPDATE SET seats_available = EXCLUDED.seats_available;

    FOR candidate IN SELECT * FROM (VALUES
        ('Stew Young', 'S. Young', 'Mayor', 9801, true),
        ('Scott Goodmanson', 'S. Goodmanson', 'Mayor', 5411, false),
        ('Lisa Foxall', 'L. Foxall', 'Councillor', 8574, true),
        ('Wendy Hobbs', 'W. Hobbs', 'Councillor', 7720, true),
        ('Bryson Hill', 'B. Hill', 'Councillor', 7533, true),
        ('Jennifer Dunnett', 'J. Dunnett', 'Councillor', 7117, true),
        ('Brandy Gordon', 'B. Gordon', 'Councillor', 6600, true),
        ('Colby Harder', 'C. Harder', 'Councillor', 6082, true),
        ('Mary Wagner', 'M. Wagner', 'Councillor', 5981, false),
        ('Keith Yacucha', 'K. Yacucha', 'Councillor', 5513, false),
        ('Kimberley Guiry', 'K. Guiry', 'Councillor', 5033, false),
        ('Tanya Sunshine', 'T. Sunshine', 'Councillor', 4966, false),
        ('Matt Sahlstrom', 'M. Sahlstrom', 'Councillor', 2843, false),
        ('Trevor Hinton', 'T. Hinton', 'Councillor', 2328, false),
        ('Shawn Blair', 'S. Blair', 'Councillor', 1772, false),
        ('Michael Mortimore', 'M. Mortimore', 'Councillor', 1386, false),
        ('Andrew Jackson', 'A. Jackson', 'Councillor', 1132, false),
        ('Alex McLeod', 'A. McLeod', 'Councillor', 772, false)
    ) AS results(full_name, initial_name, role, votes, elected)
    LOOP
        -- Fail on ambiguous identities rather than silently linking the wrong person.
        IF (SELECT count(*) FROM people WHERE lower(name) IN (lower(candidate.full_name), lower(candidate.initial_name))) > 1 THEN
            RAISE EXCEPTION 'Multiple people match election candidate %; reconcile IDs first', candidate.full_name;
        END IF;
        SELECT id INTO person FROM people
            WHERE lower(name) IN (lower(candidate.full_name), lower(candidate.initial_name));
        IF person IS NULL THEN
            INSERT INTO people (name, is_councillor) VALUES (candidate.full_name, candidate.elected)
            ON CONFLICT (name) DO UPDATE SET is_councillor = people.is_councillor OR EXCLUDED.is_councillor
            RETURNING id INTO person;
        ELSIF candidate.elected THEN
            UPDATE people SET is_councillor = true WHERE id = person;
        END IF;

        SELECT id INTO office_id FROM election_offices WHERE election_id = election_2026 AND office = candidate.role;
        INSERT INTO candidacies (election_office_id, person_id, is_elected, votes_received)
        VALUES (office_id, person, candidate.elected, candidate.votes)
        ON CONFLICT (election_office_id, person_id) DO UPDATE SET
            is_elected = CASE WHEN (SELECT results_status FROM elections WHERE id = election_2026) = 'official' THEN candidacies.is_elected ELSE EXCLUDED.is_elected END,
            votes_received = CASE WHEN (SELECT results_status FROM elections WHERE id = election_2026) = 'official' THEN candidacies.votes_received ELSE EXCLUDED.votes_received END;

        IF candidate.elected THEN
            INSERT INTO memberships (person_id, organization_id, role, start_date, council_term_id)
            SELECT person, council, candidate.role, DATE '2026-11-02', term_2026
            WHERE NOT EXISTS (SELECT 1 FROM memberships WHERE person_id = person AND organization_id = council
                AND role = candidate.role AND council_term_id = term_2026);
        END IF;
    END LOOP;
END $$;

COMMIT;
