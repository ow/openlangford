-- Voice exemplars: one CAM++ voice centroid per (meeting, diarization label) that the
-- speaker-names stage named from evidence (or a manual /speaker-alias mapping).
-- A person's voice_fingerprints row becomes the mean of their exemplars, so it grows
-- stronger with every meeting they speak at, and can be rebuilt from evidence alone.
-- Voice embeddings are biometric: service role only, like voice_fingerprints.
CREATE TABLE IF NOT EXISTS public.voice_exemplars (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id bigint NOT NULL REFERENCES public.people(id) ON DELETE CASCADE,
  meeting_id bigint NOT NULL REFERENCES public.meetings(id) ON DELETE CASCADE,
  speaker_label text NOT NULL,
  embedding jsonb NOT NULL,
  source text NOT NULL CHECK (source IN ('manual', 'evidence', 'voice')),
  confidence double precision NOT NULL DEFAULT 0.5,
  speech_seconds double precision,
  evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (meeting_id, speaker_label)
);

CREATE INDEX IF NOT EXISTS voice_exemplars_person_idx ON public.voice_exemplars (person_id);

DROP TRIGGER IF EXISTS set_timestamp_voice_exemplars ON public.voice_exemplars;
CREATE TRIGGER set_timestamp_voice_exemplars BEFORE UPDATE ON public.voice_exemplars
  FOR EACH ROW EXECUTE PROCEDURE update_timestamp();

ALTER TABLE public.voice_exemplars ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.voice_exemplars FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.voice_exemplars TO service_role;

-- Fingerprint provenance. Existing rows (and the /speaker-alias page, which does not
-- set it) are manual mappings; the pipeline writes 'aggregate' rows.
ALTER TABLE public.voice_fingerprints
  ADD COLUMN IF NOT EXISTS source text NOT NULL DEFAULT 'manual',
  ADD COLUMN IF NOT EXISTS exemplar_count integer,
  ADD COLUMN IF NOT EXISTS meeting_count integer;
