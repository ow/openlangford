"""Generate pipeline/db_rows.py: TypedDict row models from the live schema.

Run from apps/pipeline:  uv run python tools/gen_rows.py [--check]

Reads information_schema.columns over DATABASE_URL in ONE read-only transaction
(``set_session(readonly=True)`` sends ``BEGIN READ ONLY`` with the transaction, then the
transaction is rolled back). Never use a plain session-level SET on that URL: see
pipeline/db.py. ``--check`` writes nothing and exits 1 if the committed file is stale.

Rows are ``total=False``: PostgREST ``.select("a, b")`` returns subsets of columns.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from pipeline import db  # noqa: E402

OUT = ROOT / "pipeline" / "db_rows.py"
TABLES = ["matters", "agenda_items", "motions", "meetings", "document_sections"]

PY_TYPES = {
    "smallint": "int", "integer": "int", "bigint": "int",
    "real": "float", "double precision": "float", "numeric": "float",
    "boolean": "bool",
    "text": "str", "character varying": "str", "character": "str", "uuid": "str",
    "date": "str", "time without time zone": "str",
    "timestamp without time zone": "str", "timestamp with time zone": "str",
    "json": "Any", "jsonb": "Any",
    "ARRAY": "list[Any]",
    "USER-DEFINED": "str",  # pgvector columns come back from PostgREST as strings
}

HEADER = '''"""Row models for the pipeline's most-read tables. GENERATED by tools/gen_rows.py: do not edit.

``total=False`` because ``.select("a, b")`` returns only the columns asked for.
"""

from __future__ import annotations

from typing import Any, TypedDict
'''


def fetch_columns(tables: list[str]) -> dict[str, list[tuple[str, str, bool]]]:
    conn = db.connect()
    try:
        conn.set_session(readonly=True)
        with conn.cursor() as cur:
            cur.execute(
                "SELECT table_name, column_name, data_type, is_nullable = 'YES' "
                "FROM information_schema.columns "
                "WHERE table_schema = 'public' AND table_name = ANY(%s) "
                "ORDER BY table_name, ordinal_position",
                (tables,),
            )
            rows = cur.fetchall()
    finally:
        conn.rollback()
        conn.close()
    out: dict[str, list[tuple[str, str, bool]]] = {t: [] for t in tables}
    for table, column, data_type, nullable in rows:
        out[table].append((column, data_type, nullable))
    return out


def class_name(table: str) -> str:
    return "".join(part.title() for part in table.split("_")) + "Row"


def render(columns: dict[str, list[tuple[str, str, bool]]]) -> str:
    parts = [HEADER]
    for table in TABLES:
        cols = columns[table]
        if not cols:
            raise SystemExit(f"table {table!r} not found in the public schema")
        lines = [f"\n\nclass {class_name(table)}(TypedDict, total=False):"]
        for name, data_type, nullable in cols:
            py = PY_TYPES.get(data_type, "Any")
            if nullable and py != "Any":
                py += " | None"
            lines.append(f"    {name}: {py}")
        parts.append("\n".join(lines) + "\n")
    return "".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if the committed file is stale")
    args = parser.parse_args()
    text = render(fetch_columns(TABLES))
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.name} is stale: run uv run python tools/gen_rows.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(TABLES)} tables)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
