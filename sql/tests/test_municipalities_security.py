"""Public municipality access contract against disposable PostgreSQL 17."""
from pathlib import Path

from postgres_case import PostgresCase

MIGRATION = Path(__file__).resolve().parents[2] / "supabase/migrations/20261022053126_47_18_municipalities_public_read_only.sql"


class MunicipalitiesSecurity(PostgresCase):
    def test_public_reads_server_writes_and_safe_replay(self):
        # Reproduce the live table/sequence permissions with synthetic data.
        self.sql("""
          CREATE ROLE anon;
          CREATE ROLE authenticated;
          CREATE ROLE service_role BYPASSRLS;
          GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
          CREATE TABLE public.municipalities (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            slug text UNIQUE NOT NULL, name text NOT NULL
          );
          GRANT ALL ON public.municipalities TO anon, authenticated, service_role;
          GRANT ALL ON SEQUENCE public.municipalities_id_seq TO anon, authenticated, service_role;
          INSERT INTO municipalities(slug,name) VALUES ('fixture','Fixture City');
          SET ROLE anon;
          UPDATE municipalities SET name='Baseline unauthorized mutation';
          RESET ROLE;
        """)
        self.assertEqual(self.sql("SELECT name FROM municipalities")[0], "Baseline unauthorized mutation")

        for attempt in range(2):
            with self.subTest(migration_application=attempt + 1):
                self.sql(MIGRATION.read_text())
                for role in ("anon", "authenticated"):
                    with self.subTest(role=role):
                        self.assertEqual(self.sql(f"SET ROLE {role}; SELECT slug FROM municipalities")[0], "SET\nfixture")
                        for operation in (
                            "INSERT INTO municipalities(slug,name) VALUES ('blocked','Blocked')",
                            "UPDATE municipalities SET name='Blocked' WHERE slug='fixture'",
                            "DELETE FROM municipalities WHERE slug='fixture'",
                            "TRUNCATE municipalities",
                            "SELECT nextval('municipalities_id_seq')",
                        ):
                            _, error = self.sql(f"SET ROLE {role}; {operation}", success=False)
                            self.assertIn("permission denied", error)
                # Service clients retain their identity sequence and bypass RLS.
                self.sql("""
                  SET ROLE service_role;
                  INSERT INTO municipalities(slug,name) VALUES ('service','Service City');
                  UPDATE municipalities SET name='Service changed' WHERE slug='service';
                  DELETE FROM municipalities WHERE slug='service';
                """)
                self.assertEqual(self.sql("SELECT count(*) FROM municipalities")[0], "1")
