"""Run with python3 -m unittest discover -s sql/tests (requires Docker).

Uses a disposable PostgreSQL container with no ports or production credentials.
The minimal schema isolates the correction's scope and abort guarantees.
"""
import pathlib
import subprocess
import time
import unittest
import uuid

ROOT = pathlib.Path(__file__).resolve().parents[2]
CORRECTION = "SET openlangford.correction_meeting_id = '1';\n" + (
    ROOT / "sql/corrections/langford-2026-inauguration.sql"
).read_text()


from postgres_case import PostgresCase


class InaugurationCorrection(PostgresCase):
    def setUp(self):
        self.sql("""
          DROP SCHEMA public CASCADE; CREATE SCHEMA public;
          CREATE TYPE meeting_type AS ENUM ('Regular Council', 'Special Council');
          CREATE TABLE municipalities(id bigint PRIMARY KEY, slug text);
          CREATE TABLE organizations(id bigint PRIMARY KEY, municipality_id bigint,
            name text, classification text);
          CREATE TABLE meetings(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            municipality_id bigint, organization_id bigint, title text, slug text,
            meeting_date date, type meeting_type, status text DEFAULT 'Planned',
            archive_path text, has_agenda boolean DEFAULT false,
            has_minutes boolean DEFAULT false, has_transcript boolean DEFAULT false,
            summary text);
          INSERT INTO municipalities VALUES (1, 'langford'), (2, 'other');
          INSERT INTO organizations VALUES (1, 1, 'Council', 'Council');
        """)
        self.sql((ROOT / "supabase/migrations/20261020150531_47_14_inauguration_meeting_type.sql").read_text())

    def placeholder(self, extra=""):
        self.sql("""INSERT INTO meetings(municipality_id, organization_id, title, slug,
          meeting_date, type) VALUES (1, 1, 'Regular Council', 'keep-existing-url',
          '2026-11-02', 'Regular Council');""" + extra)

    def test_missing_event_is_never_created(self):
        _, error = self.sql(CORRECTION, success=False)
        self.assertIn("No November 2 placeholder exists", error)
        rows, _ = self.sql("SELECT count(*) FROM meetings")
        self.assertEqual(rows, "0")

    def test_unverified_id_aborts(self):
        self.placeholder()
        _, error = self.sql(CORRECTION.split("\n", 1)[1], success=False)
        self.assertIn("Set the verified placeholder ID", error)
        rows, _ = self.sql("SELECT title FROM meetings")
        self.assertEqual(rows, "Regular Council")

    def test_wrong_verified_id_aborts(self):
        self.placeholder()
        _, error = self.sql(CORRECTION.replace("= '1'", "= '999'"), success=False)
        self.assertIn("does not match the verified ID", error)
        rows, _ = self.sql("SELECT title FROM meetings")
        self.assertEqual(rows, "Regular Council")

    def test_corrects_placeholder_preserving_identity_and_other_events(self):
        self.placeholder("""INSERT INTO meetings(municipality_id, title, meeting_date, type)
          VALUES (2, 'Other council', '2026-11-02', 'Regular Council'),
                 (1, 'Other date', '2026-11-16', 'Regular Council');""")
        self.sql(CORRECTION)
        self.sql(CORRECTION)
        rows, _ = self.sql("SELECT id, title, type, slug FROM meetings ORDER BY id")
        self.assertEqual(rows.splitlines(), [
            "1|Inauguration|Inauguration|keep-existing-url",
            "2|Other council|Regular Council|", "3|Other date|Regular Council|",
        ])

    def test_ambiguous_events_abort_without_changing_either(self):
        self.placeholder("""INSERT INTO meetings(municipality_id, organization_id, title,
          meeting_date, type) VALUES (1, 1, 'Second event', '2026-11-02', 'Special Council');""")
        _, error = self.sql(CORRECTION, success=False)
        self.assertIn("Ambiguous November 2 council events", error)
        rows, _ = self.sql("SELECT count(*) FROM meetings WHERE type = 'Inauguration'")
        self.assertEqual(rows, "0")

    def test_content_and_cancelled_events_require_review(self):
        for assignment in ["has_agenda = true", "has_minutes = true", "has_transcript = true",
                           "summary = 'Existing summary'", "archive_path = 'archive/event'",
                           "status = 'Cancelled'"]:
            with self.subTest(assignment=assignment):
                self.sql("TRUNCATE meetings RESTART IDENTITY")
                self.placeholder("UPDATE meetings SET " + assignment)
                _, error = self.sql(CORRECTION, success=False)
                self.assertIn("event has content or is cancelled", error)
                rows, _ = self.sql("SELECT title, type FROM meetings")
                self.assertEqual(rows, "Regular Council|Regular Council")
