"""Actual PostgreSQL contract tests for trusted schedule publication and identity."""
import json
from pathlib import Path
from postgres_case import PostgresCase

MIGRATION = Path(__file__).resolve().parents[2] / 'supabase/migrations/20261020161233_47_15_calendar_sync.sql'


class CalendarSync(PostgresCase):
    def setUp(self):
        self.sql("""
          DROP SCHEMA public CASCADE; CREATE SCHEMA public;
          DO $$ BEGIN
            IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='anon') THEN CREATE ROLE anon; END IF;
            IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN CREATE ROLE authenticated; END IF;
            IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='service_role') THEN CREATE ROLE service_role; END IF;
          END $$;
          CREATE TYPE meeting_type AS ENUM ('Regular Council','Special Council','Inauguration','Committee of the Whole','Public Hearing','Advisory Committee');
          CREATE TABLE municipalities(id bigint PRIMARY KEY,slug text);
          CREATE TABLE organizations(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name text UNIQUE,municipality_id bigint,classification text);
          CREATE TABLE meetings(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,municipality_id bigint,organization_id bigint,
            title text,slug text DEFAULT gen_random_uuid()::text,meeting_date date,type meeting_type,status text,
            meta jsonb,archive_path text,has_agenda boolean DEFAULT false,has_minutes boolean DEFAULT false,
            has_transcript boolean DEFAULT false,summary text);
          CREATE TABLE source_meetings(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,municipality_id bigint,
            source_type text,source_id text,meeting_date date,title text,meeting_type text,source_url text,
            raw jsonb,status text,last_seen_at timestamptz DEFAULT now(),ingested_meeting_id bigint REFERENCES meetings(id),
            UNIQUE(municipality_id,source_type,source_id));
          INSERT INTO municipalities VALUES(1,'langford'),(2,'other');
          INSERT INTO organizations(name,municipality_id,classification) VALUES('Council',1,'Council');
        """)
        self.sql(MIGRATION.read_text())
        self.sql((MIGRATION.parent / "20261020162205_47_16_calendar_document_reconciliation.sql").read_text())
        self.date = self.sql("SELECT ((now() AT TIME ZONE 'America/Vancouver')::date+7)::text")[0]
        self.event = dict(source_type='official_schedule', source_id='reviewed-entry', meeting_date=self.date,
                          title='Regular Council', type='Regular Council', organization_name='Council',
                          source_url='https://langford.ca/wp-content/uploads/2025/12/2026-Council-Year-Calendar-Council-Committees.pdf',
                          start_time='19:00', cancelled=False)

    def apply(self, events, success=True):
        token = self.sql('SELECT claim_calendar_sync()')[0]
        encoded = json.dumps(events).replace("'", "''")
        return self.sql(f"SELECT apply_calendar_sync('{token}','{encoded}'::jsonb)", success=success)

    def test_retry_and_document_arrival_keep_id_slug_content_and_calendar_link(self):
        result, _ = self.apply([self.event])
        self.assertEqual(json.loads(result)['created'], 1)
        before = self.sql('SELECT id,slug FROM meetings')[0]
        self.apply([self.event])
        feed = {**self.event, 'source_type':'escribe', 'source_id':'published-guid',
                'source_url':'https://pub-langford.escribemeetings.com/meetingscalendarview.aspx'}
        self.apply([feed])
        self.assertEqual(self.sql('SELECT id,slug FROM meetings')[0], before)
        self.assertEqual(self.sql('SELECT count(DISTINCT ingested_meeting_id) FROM source_meetings')[0], '1')
        self.sql("UPDATE meetings SET archive_path='archive/published',has_minutes=true,summary='Actual recorded content',status='Completed'")
        self.apply([feed])
        self.assertEqual(self.sql('SELECT summary,status,has_minutes FROM meetings')[0], 'Actual recorded content|Completed|t')
        self.assertEqual(self.sql('SELECT count(*) FROM meetings')[0], '1')

    def test_overlap_and_expired_runner_cannot_write(self):
        first = self.sql('SELECT claim_calendar_sync()')[0]
        self.assertEqual(self.sql('SELECT claim_calendar_sync()')[0], '')
        self.sql("UPDATE calendar_sync_state SET lease_until=now()-interval '1 second'")
        second = self.sql('SELECT claim_calendar_sync()')[0]
        self.assertNotEqual(first, second)
        _, error = self.sql(f"SELECT apply_calendar_sync('{first}','[]')", success=False)
        self.assertIn('query returned no rows', error)
        self.assertEqual(self.sql('SELECT count(*) FROM meetings')[0], '0')

    def test_historical_unknown_source_and_untrusted_public_call_are_rejected(self):
        past = self.sql("SELECT ((now() AT TIME ZONE 'America/Vancouver')::date-1)::text")[0]
        for changed in [{'meeting_date':past},{'source_url':'https://example.org/fake'},{'type':None}]:
            with self.subTest(changed=changed):
                self.sql('TRUNCATE calendar_sync_state')
                self.apply([{**self.event,**changed}], success=False)
                self.assertEqual(self.sql('SELECT count(*) FROM meetings')[0], '0')
        self.sql('GRANT USAGE ON SCHEMA public TO anon')
        _, error = self.sql('SET ROLE anon; SELECT claim_calendar_sync()',success=False)
        self.assertIn('permission denied',error)

    def test_explicit_cancellation_only_and_no_absence_deletion(self):
        self.apply([self.event])
        self.apply([])
        self.assertEqual(self.sql('SELECT status FROM meetings')[0], 'Planned')
        self.apply([{**self.event,'cancelled':True}])
        self.apply([self.event])
        self.assertEqual(self.sql('SELECT status FROM meetings')[0], 'Cancelled')

    def test_multiple_same_day_published_events_are_held_instead_of_merged(self):
        self.apply([self.event])
        feed = {**self.event,'source_type':'escribe','source_url':'https://pub-langford.escribemeetings.com/meetingscalendarview.aspx'}
        result,_=self.apply([{**feed,'source_id':'first'},{**feed,'source_id':'second'}])
        self.assertEqual(json.loads(result)['held'],2)
        self.assertEqual(self.sql('SELECT count(*) FROM meetings')[0], '1')
        self.assertEqual(self.sql("SELECT count(*) FROM source_meetings WHERE source_type='escribe' AND ingested_meeting_id IS NOT NULL")[0], '0')

    def test_feed_reschedule_outweighs_old_annual_schedule(self):
        self.apply([self.event])
        feed={**self.event,'source_type':'escribe','source_id':'published',
              'source_url':'https://pub-langford.escribemeetings.com/meetingscalendarview.aspx'}
        self.apply([feed])
        moved=self.sql("SELECT ((now() AT TIME ZONE 'America/Vancouver')::date+9)::text")[0]
        self.apply([{**feed,'meeting_date':moved},self.event])
        self.assertEqual(self.sql('SELECT meeting_date FROM meetings')[0],moved)
        self.assertEqual(self.sql('SELECT count(*) FROM meetings')[0],'1')

    def test_unmapped_possible_reschedule_is_held_without_creating_a_duplicate(self):
        self.apply([self.event])
        moved=self.sql("SELECT ((now() AT TIME ZONE 'America/Vancouver')::date+9)::text")[0]
        feed={**self.event,'source_type':'escribe','source_id':'unmapped-published','meeting_date':moved,
              'source_url':'https://pub-langford.escribemeetings.com/meetingscalendarview.aspx'}
        result,_=self.apply([feed])
        self.assertEqual(json.loads(result)['held'],1)
        self.assertEqual(self.sql('SELECT count(*) FROM meetings')[0],'1')
        self.assertEqual(self.sql('SELECT meeting_date FROM meetings')[0],self.date)

    def test_two_distinct_published_ids_can_share_one_day_without_a_schedule_placeholder(self):
        feed={**self.event,'source_type':'escribe',
              'source_url':'https://pub-langford.escribemeetings.com/meetingscalendarview.aspx'}
        result,_=self.apply([{**feed,'source_id':'first'},{**feed,'source_id':'second'}])
        self.assertEqual(json.loads(result)['created'],2)
        self.apply([{**feed,'source_id':'first'},{**feed,'source_id':'second'}])
        self.assertEqual(self.sql('SELECT count(*) FROM meetings')[0],'2')

    def test_first_published_documents_after_event_date_reuse_calendar_record(self):
        self.apply([self.event])
        before=self.sql('SELECT id,slug FROM meetings')[0]
        self.sql("UPDATE meetings SET meeting_date=(now() AT TIME ZONE 'America/Vancouver')::date-1; UPDATE source_meetings SET meeting_date=(now() AT TIME ZONE 'America/Vancouver')::date-1")
        source=self.sql("INSERT INTO source_meetings(municipality_id,source_type,source_id,meeting_date,title,meeting_type,raw,status) VALUES(1,'escribe','late-documents',(now() AT TIME ZONE 'America/Vancouver')::date-1,'Council Meeting','Regular Council','{}','discovered') RETURNING id")[0].splitlines()[0]
        target=self.sql(f'SELECT reconcile_calendar_source({source})')[0]
        self.assertEqual(target,before.split('|')[0])
        self.assertEqual(self.sql(f'SELECT reconcile_calendar_source({source})')[0],target)
        self.sql("UPDATE meetings SET archive_path='archive/published',has_agenda=true WHERE id="+target)
        self.assertEqual(self.sql('SELECT id,slug FROM meetings')[0],before)
        self.assertEqual(self.sql('SELECT count(*) FROM meetings')[0],'1')
