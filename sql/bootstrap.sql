-- First-class council terms and verified Langford election seed.
-- Council tenure is distinct from election day and from a person's identity.
-- End dates are inclusive. An unknown future term end stays NULL.

ALTER TABLE elections
    ADD COLUMN IF NOT EXISTS results_status text NOT NULL DEFAULT 'pending',
    ADD COLUMN IF NOT EXISTS source_url text;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'elections'::regclass AND conname = 'elections_results_status_check') THEN
        ALTER TABLE elections ADD CONSTRAINT elections_results_status_check
            CHECK (results_status IN ('pending', 'preliminary', 'official'));
    END IF;
END $$;

